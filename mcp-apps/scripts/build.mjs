// Bundles each view into one self-contained HTML file in cmd/zv-mcp/apps, which zv-mcp embeds.
// Hosts load MCP Apps under a CSP that blocks the network, so the script and style go inline.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const VIEWS = [{ name: "job-progress", title: "Progreso de ClipHub Studio" }];
const root = fileURLToPath(new URL("..", import.meta.url));
const outDir = fileURLToPath(new URL("../../cmd/zv-mcp/apps/", import.meta.url));

for (const view of VIEWS) {
  const result = await build({
    entryPoints: [`${root}src/${view.name}/main.tsx`],
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2022",
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"' },
    legalComments: "none",
    write: false,
  });
  const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
  const css = await readFile(`${root}src/${view.name}/style.css`, "utf8");
  const html = `<!doctype html>
<!-- Generated by mcp-apps/scripts/build.mjs from mcp-apps/src/${view.name}. Do not edit. -->
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${view.title}</title>
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;
  await writeFile(`${outDir}${view.name}.html`, html);
  console.log(`${view.name}.html: ${(html.length / 1024).toFixed(0)} KB`);
}
