package httpapi

import (
	"net/http"
	"slices"
)

// Route is one method and pattern that Routes registers.
type Route struct {
	Method  string
	Pattern string
}

// AnalysisRoutes returns the routes both editions serve: the library, its
// analysis and the map assets. The ClipMind web server opens exactly these, so
// analysis stays the same in Studio and on the web. Every library, map and team
// route is either here or in desktopOnlyRoutes (edition_routes_test.go).
func AnalysisRoutes() []Route {
	return slices.Clone(analysisRoutes)
}

func get(pattern string) Route   { return Route{http.MethodGet, pattern} }
func post(pattern string) Route  { return Route{http.MethodPost, pattern} }
func put(pattern string) Route   { return Route{http.MethodPut, pattern} }
func patch(pattern string) Route { return Route{http.MethodPatch, pattern} }
func del(pattern string) Route   { return Route{http.MethodDelete, pattern} }

